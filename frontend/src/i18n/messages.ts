export const messages: Record<Locale, typeof id> = { id, en };

export function translate(locale: Locale, key: keyof typeof id, vars?: Record<string, string | number>) {
  let text: string = messages[locale][key] ?? messages.id[key];
  if (vars) {
    Object.entries(vars).forEach(([name, value]) => {
      text = text.replace(`{${name}}`, String(value));
    });
  }
  return text;
}
